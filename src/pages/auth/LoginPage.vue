<script setup>
import { ref } from 'vue'
import { auth, db } from 'src/boot/firebase'
import { signInWithEmailAndPassword } from 'firebase/auth'
import { collection, query, where, getDocs, setDoc, doc } from 'firebase/firestore'
import { useRouter } from 'vue-router'
import { useAuthStore } from 'src/stores/auth'
import { useQuasar } from 'quasar'

const email = ref('refqiobeth345@gmail.com')
const password = ref('')
const showPwd = ref(false)
const rememberMe = ref(true)
const loading = ref(false)
const errorMsg = ref('')

const router = useRouter()
const authStore = useAuthStore()
const $q = useQuasar()

const handleLogin = async () => {
  if (!email.value || !password.value) {
    errorMsg.value = 'Email dan Password wajib diisi!'
    return
  }

  loading.value = true
  errorMsg.value = ''

  try {
    // 1. Autentikasi via Firebase Auth
    const cred = await signInWithEmailAndPassword(auth, email.value, password.value)

    // 2. Ambil data karyawan dari Firestore
    const q = query(collection(db, 'karyawan'), where('email', '==', email.value.toLowerCase()))
    const snapshot = await getDocs(q)

    let userData = {}

    if (snapshot.empty) {
      // Jika belum ada dokumen karyawan, buat otomatis (Super Admin fallback)
      userData = {
        nama: cred.user.displayName || 'User',
        email: email.value.toLowerCase(),
        role: 'Super Admin',
        jabatan: 'Super Admin',
        uid: cred.user.uid,
        akses: ['konstruksi', 'absensi', 'manufaktur', 'admin', 'aset'],
      }
      await setDoc(doc(collection(db, 'karyawan')), userData)
    } else {
      userData = snapshot.docs[0].data()
    }

    // 3. Simpan ke store & localStorage
    authStore.setLogin(userData, userData.akses)

    if (rememberMe.value) {
      localStorage.setItem('user_data', JSON.stringify(userData))
    }

    // 4. Notifikasi sukses & redirect
    $q.notify({
      color: 'positive',
      message: `Selamat datang, ${userData.nama || 'User'}!`,
      icon: 'verified',
      position: 'top',
      timeout: 2000,
    })

    router.push('/')
  } catch (e) {
    // Mapping error code Firebase ke pesan Indonesia
    const errorMap = {
      'auth/user-not-found': 'Akun tidak ditemukan!',
      'auth/wrong-password': 'Password salah!',
      'auth/invalid-credential': 'Email atau password tidak valid!',
      'auth/invalid-email': 'Format email tidak valid!',
      'auth/user-disabled': 'Akun ini telah dinonaktifkan!',
      'auth/too-many-requests': 'Terlalu banyak percobaan. Coba lagi nanti.',
      'auth/network-request-failed': 'Koneksi internet bermasalah!',
    }
    errorMsg.value = errorMap[e.code] || `Login gagal: ${e.message}`

    $q.notify({
      color: 'negative',
      message: errorMsg.value,
      icon: 'report_problem',
      position: 'bottom',
      timeout: 3000,
    })
  } finally {
    loading.value = false
  }
}
</script>

